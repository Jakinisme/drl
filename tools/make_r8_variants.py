#!/usr/bin/env python
"""R8 variant scaffolding: configs/r8/env_{control,A,B}.yaml + train_{control,A,B}.yaml.

    ./.venv/Scripts/python.exe tools/make_r8_variants.py            # write
    ./.venv/Scripts/python.exe tools/make_r8_variants.py --verify   # check bytes on disk
    ./.venv/Scripts/python.exe tools/make_r8_variants.py --verify --json

Edits are LINE-level on the reward block of configs/env.yaml, so comments and key order
survive and the output is byte-deterministic (re-running rewrites identical bytes).

The two R8-only keys that need a comment (`arrive_gate_floor`, `settle_speed_ref_mps`)
are injected into the block of existing keys (`w_arrival`, `w_position_fine`); the rest
land in a marked `# --- R8 ---` appendix at the end of the reward block. `control` lands
every value so the PRE-R8 formula is reproduced exactly -- see PRE_R8_NOTES.

Refuses to overwrite any file in configs/r8/ it did not generate (unknown name, or no
GENERATED banner as its first line).
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SRC_ENV = ROOT / "configs" / "env.yaml"
SRC_TRAIN = ROOT / "configs" / "train.yaml"
OUT_DIR = ROOT / "configs" / "r8"
BANNER = ("# AUTO-GENERATED by tools/make_r8_variants.py from {src} -- do not hand-edit, "
          "edit the generator.")
TAG = "  # TODO T8 placeholder, untuned"
TODO = {"w_hold", "w_sat"}          # new weights: no module-level key of their own

# Inserted right after the copied line for the first key that already exists in the block.
INJECT: dict[str, list[str]] = {
    "w_arrival": [
        # gate() must equal 1.0 for every reachable speed: exp(-(speed/ref)^2).  The soft
        # cap is max_surge_mps = 1.0 (configs/vehicle.yaml) and nothing in the plant lets
        # speed pass ~1.0 m/s.  NOT 1e6: in float32 the ratio is not small enough and gate
        # returns 0.999999, i.e. the control arm would no longer match the pre-R8 reward.
        # 1e20 gives exactly 1.0 for every |v| < 1e18.  It is written as DIGITS, not as
        # "1e20", because PyYAML parses an exponent-without-dot as a STRING -- which made
        # _gate see a str and silently return 1.0 for every speed.
        "arrive_gate_floor",
        "settle_speed_ref_mps",
    ],
}

# Annotate the two R8 keys the pre-R8 env never read, on the control arm only.
# Pre-R8 env has no gate and no sat term at all; on the control arm the gate is a constant
# 1.0 (ref >> top speed) and both new weights are 0, so the formula is the R4 one exactly.
PRE_R8_NOTES = {
    "arrive_gate_floor": "  # pre-R8: gate() is constant 1.0 (R4 gate), this floor never binds",
    "settle_speed_ref_mps": "  # pre-R8: no speed gate; 1e6 >> top speed -> gate() == 1.0 always",
}
# Appendix order for keys with no sibling in the reward block.
R8_ORDER = ["w_hold", "hold_radius_m", "w_sat", "w_cross_track", "w_action_rate",
            "w_energy", "w_near_goal_speed", "arrive_gate_floor", "settle_speed_ref_mps"]

VARIANTS: dict[str, dict] = {
    "control": {
        "w_hold": "0",              # PRE-R8 reward EXACTLY: both new terms OFF ...
        "w_sat": "0",
        "arrive_gate_floor": "1.0",  # ... and the arrival gate permanently open (== R4 gate)
        # Digits, not "1e20": PyYAML reads a bare exponent as a str. See the comment above.
        "settle_speed_ref_mps": "100000000000000000000",
    },
    "A": {
        "arrive_gate_floor": "0.3",
        "settle_speed_ref_mps": "0.4",
        "w_hold": "0.5",
        "hold_radius_m": "1.5",
        "w_sat": "0.1",
        "w_action_rate": "0.15",
        "w_energy": "0.02",
        "w_near_goal_speed": "0.3",
    },
    "B": {
        "arrive_gate_floor": "0.15",
        "settle_speed_ref_mps": "0.25",
        "w_hold": "1.0",
        "hold_radius_m": "1.0",
        "w_sat": "0.20",
        "w_action_rate": "0.20",
        "w_energy": "0.02",
        "w_near_goal_speed": "0.5",
    },
}

TRAIN_OVERRIDES = {
    "total_steps": "10000000",
    "save_interval_steps": "2000000",
    "seed": "0",
    "log_dir": "runs/r8_{name}",
    "ckpt_dir": "runs/r8_{name}/ckpt",
}


class Refuse(Exception):
    pass


# ------------------------------------------------------------------ yaml line surgery
def _lines(path: Path) -> list[str]:
    return path.read_text(encoding="utf-8").splitlines(keepends=True)


def _block(lines: list[str], key: str, indent: int = 0) -> tuple[int, int]:
    """`<indent><key>:` at indent `indent`, and the value/comment right after its colon."""
    pad = " " * indent
    head = f"{pad}{key}:"
    start = next((i for i, ln in enumerate(lines)
                  if ln.startswith(head) and (len(ln) == len(head)
                                              or ln[len(head)] in " \t#\r\n")), None)
    if start is None:
        raise Refuse(f"`{key}:` block not found")
    end = start + 1
    while end < len(lines):
        ln = lines[end]
        if ln.strip() == "" or ln.lstrip().startswith("#"):
            end += 1
            continue
        if len(ln) - len(ln.lstrip(" ")) > indent:
            end += 1
            continue
        break
    return start + 1, end


def _split(ln: str) -> tuple[str, str, str]:
    """`  key: value   # comment` -> ("  ", "key", "# comment")  (value dropped)."""
    pad = ln[: len(ln) - len(ln.lstrip(" "))]
    body = ln.strip()
    key, _, rest = body.partition(":")
    cut = rest.find("#")
    return pad, key.strip(), (rest[cut:].strip() if cut >= 0 else "")


def _find(body: list[str], key: str) -> int | None:
    """Index of the first non-comment line whose key is exactly `key`."""
    for i, ln in enumerate(body):
        if ln.strip() and not ln.lstrip().startswith("#") and _split(ln)[1] == key:
            return i
    return None


def _note(name: str, key: str) -> str:
    if key in TODO:
        return TAG
    return PRE_R8_NOTES.get(key, "") if name == "control" else ""


def patch_env(src_lines: list[str], name: str) -> list[str]:
    changes = VARIANTS[name]
    a, b = _block(src_lines, "reward", 0)      # top-level block (its children sit at 2)
    body = src_lines[a:b]
    is_control = name == "control"

    # 1) values: existing keys -> in place (comment kept unless the value's meaning changed)
    seen: set[str] = set()
    for i, ln in enumerate(body):
        if not ln.strip() or ln.lstrip().startswith("#"):
            continue
        pad, key = _split(ln)[:2]
        if key in changes:
            body[i] = f"{pad}{key}: {changes[key]}{_note(name, key)}\n"
            seen.add(key)

    # 2) R8 keys with a sibling already in the block -> injected right after it
    injected: list[tuple[int, str]] = []
    for host, entries in INJECT.items():
        for key in entries:
            if key not in changes or key in seen:
                continue
            idx = _find(body, host)
            if idx is None:
                raise Refuse(f"variant {name}: host key `{host}` missing from the reward block")
            injected.append((idx + 1, f"{_split(body[idx])[0]}{key}: {changes[key]}{_note(name, key)}\n"))
            seen.add(key)

    # 3) the rest -> appendix at the end of the block
    tail = [f"  {key}: {changes[key]}{_note(name, key)}\n"
            for key in R8_ORDER
            if key in changes and key not in seen]

    for pos, txt in sorted(injected, key=lambda t: -t[0]):
        body.insert(pos, txt)

    if tail:
        if body and body[-1].strip():
            body.append("\n")
        body.append("  # --- R8 reward redesign (reports/R8.md); keys above are copied through ---\n")
        body.extend(tail)

    header = [
        BANNER.format(src="configs/env.yaml") + "\n",
        f"# variant: {name} -- only `reward:` differs from configs/env.yaml\n",
    ]
    return header + src_lines[:a] + body + src_lines[b:]


def patch_train(src_lines: list[str], name: str) -> list[str]:
    out, seen = [], set()
    for ln in src_lines:
        s = ln.strip()
        if s and not s.startswith("#"):
            key = s.partition(":")[0].strip()
            if key in TRAIN_OVERRIDES:
                pad = ln[: len(ln) - len(ln.lstrip(" "))]
                out.append(f"{pad}{key}: {TRAIN_OVERRIDES[key].format(name=name)}\n")
                seen.add(key)
                continue
            if key == "env_config":
                pad = ln[: len(ln) - len(ln.lstrip(" "))]
                out.append(f"{pad}env_config: configs/r8/env_{name}.yaml\n")
                seen.add("env_config")
                continue
        out.append(ln)
    missing = (set(TRAIN_OVERRIDES) | {"env_config"}) - seen
    if missing:
        raise Refuse(f"configs/train.yaml is missing keys: {sorted(missing)}")
    header = [BANNER.format(src="configs/train.yaml") + "\n",
              f"# variant: {name} -- only env_config/total_steps/save_interval_steps/"
              f"seed/log_dir/ckpt_dir differ\n"]
    return header + out


# ------------------------------------------------------------------ write / verify
def render() -> dict[str, str]:
    env_src, train_src = _lines(SRC_ENV), _lines(SRC_TRAIN)
    files: dict[str, str] = {}
    for name in VARIANTS:
        files[f"env_{name}.yaml"] = "".join(patch_env(env_src, name))
        files[f"train_{name}.yaml"] = "".join(patch_train(train_src, name))
    return files


GENERATED = {"env_control.yaml", "env_A.yaml", "env_B.yaml",
             "train_control.yaml", "train_A.yaml", "train_B.yaml"}


def guard() -> None:
    if not OUT_DIR.exists():
        return
    for path in sorted(OUT_DIR.iterdir()):
        if not path.is_file():
            continue
        if path.name not in GENERATED:
            raise Refuse(f"{path.relative_to(ROOT)} is not generated by this script")
        head = path.read_text(encoding="utf-8").splitlines()[:1]
        if not head or not head[0].startswith("# AUTO-GENERATED by tools/make_r8_variants.py"):
            raise Refuse(f"{path.relative_to(ROOT)} exists but carries no GENERATED banner")


def write() -> int:
    files = render()
    guard()
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name in sorted(files):
        path = OUT_DIR / name
        path.write_text(files[name], encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT).as_posix()} "
              f"({len(files[name].encode()):d} B)")
    return 0


def verify() -> tuple[int, list[str]]:
    src_env = yaml.safe_load(SRC_ENV.read_text(encoding="utf-8"))
    src_train = yaml.safe_load(SRC_TRAIN.read_text(encoding="utf-8"))
    prob = src_env["reward"]
    rows: list[str] = []
    bad: list[str] = []

    def chk(cond: bool, msg: str) -> None:
        if not cond:
            bad.append(msg)

    envs = {}
    for name in VARIANTS:
        path = OUT_DIR / f"env_{name}.yaml"
        chk(path.exists(), f"missing {path.name}")
        if not path.exists():
            continue
        envs[name] = yaml.safe_load(path.read_text(encoding="utf-8"))["reward"]

    if "control" in envs:
        ctl = envs["control"]
        rows.append("(a) control vs configs/env.yaml reward block")
        for key, val in prob.items():
            ok = key in ctl and abs(float(ctl[key]) - float(val)) < 1e-12
            chk(ok, f"control: original reward key {key} = {ctl.get(key)!r}, want {val!r}")
            rows.append(f"    {key:<22} {val!r:>8}  {'OK' if ok else 'FAIL'}")
        for key in VARIANTS["control"]:
            chk(key in ctl, f"control: R8 key {key} not explicit")
            rows.append(f"    {key:<22} {'--':>8}  {'OK' if key in ctl else 'FAIL'}"
                        f"  (R8 key explicit = {ctl.get(key)!r})")
        chk(float(ctl["w_hold"]) == 0.0 and float(ctl["w_sat"]) == 0.0,
            "control: new terms not off")
        chk(float(ctl["arrive_gate_floor"]) == 1.0 and float(ctl["settle_speed_ref_mps"]) >= 1e3,
            "control: arrival gate not permanently open")

    rows.append("")
    rows.append("(b) A / B vs control: changed keys only")
    allkeys = sorted({k for v in envs.values() for k in v} | set(prob))
    rows.append("    " + "key".ljust(22) + "".join(n.ljust(10) for n in VARIANTS))
    for key in allkeys:
        vals = [envs.get(n, {}).get(key) for n in VARIANTS]
        cells = "".join("-".center(10) if v is None else repr(v).ljust(10) for v in vals)
        changed = len({repr(v) for v in vals}) > 1
        rows.append(f"    {key:<22}{cells}{'CHANGED' if changed else ''}")
    for name in ("A", "B"):
        if name not in envs or "control" not in envs:
            continue
        ctl, var = envs["control"], envs[name]
        for key in allkeys:
            if key not in prob:                      # an R8-only key
                want = VARIANTS[name].get(key, VARIANTS["control"].get(key))
                chk(key in var and repr(float(var[key])) == repr(float(want)),
                    f"env_{name}: {key} = {var.get(key)!r}, want {want!r}")
            elif key in VARIANTS[name]:
                chk(repr(float(var[key])) == repr(float(VARIANTS[name][key])),
                    f"env_{name}: {key} = {var.get(key)!r}, want {VARIANTS[name][key]!r}")
            else:
                chk(repr(var[key]) == repr(float(prob[key])),
                    f"env_{name}: {key} not copied through ({var[key]!r} != {prob[key]!r})")
        diff = [k for k in allkeys if repr(var.get(k)) != repr(ctl.get(k))]
        missing = [k for k in VARIANTS[name] if k not in diff or k not in var]
        chk(not missing, f"env_{name}: expected keys unchanged vs control: {missing}")
        rows.append(f"    env_{name}: differs from control in {len(diff)} keys: {diff}")

    rows.append("")
    rows.append("(c) train yamls")
    for name in VARIANTS:
        path = OUT_DIR / f"train_{name}.yaml"
        rows.append(f"    {path.name}: {'present' if path.exists() else 'MISSING'}")
        if not path.exists():
            chk(False, f"missing {path.name}")
            continue
        t = yaml.safe_load(path.read_text(encoding="utf-8"))
        envp = ROOT / t["env_config"]
        chk(envp.exists(), f"train_{name}: env_config {t['env_config']} does not resolve")
        chk(t["env_config"] == f"configs/r8/env_{name}.yaml",
            f"train_{name}: env_config = {t['env_config']!r}")
        chk(t["total_steps"] == 10_000_000, f"train_{name}: total_steps {t['total_steps']}")
        chk(t["save_interval_steps"] == 2_000_000,
            f"train_{name}: save_interval_steps {t['save_interval_steps']}")
        chk(int(t["seed"]) == 0, f"train_{name}: seed {t['seed']}")
        chk(t["log_dir"] == f"runs/r8_{name}", f"train_{name}: log_dir {t['log_dir']}")
        chk(t["ckpt_dir"] == f"runs/r8_{name}/ckpt", f"train_{name}: ckpt_dir {t['ckpt_dir']}")
        for key, val in src_train.items():
            if key in TRAIN_OVERRIDES or key == "env_config":
                continue
            chk(t.get(key) == val, f"train_{name}: {key} changed ({t.get(key)!r} != {val!r})")
        rows.append(f"    {path.name}: env_config={t['env_config']} "
                    f"total_steps={t['total_steps']} save_interval_steps="
                    f"{t['save_interval_steps']} seed={t['seed']} log_dir={t['log_dir']} "
                    f"ckpt_dir={t['ckpt_dir']} -> env file "
                    f"{'FOUND' if envp.exists() else 'MISSING'}")
        # everything else identical to configs/train.yaml
        same = all(t.get(k) == v for k, v in src_train.items()
                   if k not in TRAIN_OVERRIDES and k != "env_config")
        chk(same, f"train_{name}: non-overridden keys differ from configs/train.yaml")

    # idempotence + byte identity with the renderer
    files = render()
    for name, text in files.items():
        path = OUT_DIR / name
        on_disk = path.read_text(encoding="utf-8") if path.exists() else None
        chk(on_disk == text, f"{name}: on-disk bytes differ from the renderer (re-run the script)")
    digests = {n: hashlib.sha256(t.encode()).hexdigest()[:16] for n, t in sorted(files.items())}
    rows.append("")
    rows.append("(d) idempotence: sha256(render()) == sha256(on disk)  "
                + ("OK" if not bad else "see failures"))
    for n, d in digests.items():
        rows.append(f"    {n:<20} {d}")

    rows.append("")
    rows.append(f"RESULT: {'PASS' if not bad else 'FAIL'} ({len(bad)} failure(s))")
    for msg in bad:
        rows.append(f"    FAIL {msg}")
    return (0 if not bad else 1), rows


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--verify", action="store_true", help="check the files on disk, write nothing")
    ap.add_argument("--json", action="store_true", help="--verify output as JSON")
    args = ap.parse_args(argv)
    try:
        if not args.verify:
            return write()
        code, rows = verify()
    except Refuse as exc:
        print(f"REFUSED: {exc}", file=sys.stderr)
        return 2
    if args.json:
        import json
        print(json.dumps({"ok": code == 0, "lines": rows}, indent=2))
    else:
        print("\n".join(rows))
    return code


if __name__ == "__main__":
    raise SystemExit(main())
